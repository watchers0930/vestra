/**
 * 건물 연한(노후도) 기반 가격 성장 계수
 *
 * 건물 연한은 단순 감가가 아니라 양면적이다:
 *  - 신축(0~7년): 신축 프리미엄으로 상대적 강세
 *  - 준신축~중간(8~25년): 노후로 완만한 감가
 *  - 재건축 직전(26~29년): 사업 불확실 구간의 저점
 *  - 재건축 연한 도달(30~45년): 재건축/리모델링 기대감으로 반등 (구축이 신축보다 비싼 사례)
 *  - 초노후(46년+): 사업성 불확실로 기대감 약화
 *
 * 준공연도 기반 buildingAge(건축물대장)만으로 재건축 사업성까지는 알 수 없으므로,
 * 계수는 보수적 범위(0.94~1.03)로 제한한다.
 */
export function buildingAgeFactor(age?: number): number {
  if (age == null || !Number.isFinite(age) || age < 0) return 1;
  if (age <= 7) return 1.02;   // 신축 프리미엄
  if (age <= 15) return 1.0;   // 준신축
  if (age <= 25) return 0.97;  // 중간 노후(완만 감가)
  if (age <= 29) return 0.95;  // 재건축 직전 저점
  if (age <= 45) return 1.02;  // 재건축 연한 — 기대감 반등
  return 1.0;                  // 초노후(사업성 불확실)
}
