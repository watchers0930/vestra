function parseSido(address: string): string | null {
  const sortedKeys = Object.keys(SIDO_ALIASES).sort((a, b) => b.length - a.length);
  for (const key of sortedKeys) {
    if (address.startsWith(key) || address.includes(key)) {
      return SIDO_ALIASES[key];
    }
  }
  return null;
}

function parseGungu(address: string, sido: string): string[] {
  if (sido === "세종") return ["세종시", "세종특별자치시"];

  const candidates: string[] = [];

  // 복합 시+구 (예: 성남시분당구, 창원시의창구)
  const siGuPattern = /([가-힣]+시)\s*([가-힣]+구)/g;
  let m;
  while ((m = siGuPattern.exec(address)) !== null) {
    const [, si, gu] = m;
    if (!si.includes("광역") && !si.includes("특별") && !si.includes("자치")) {
      candidates.unshift(`${si}${gu}`);
    }
  }

  // 구
  const guMatch = address.match(/[가-힣]+구(?=[\s,]|$)/g);
  if (guMatch) candidates.push(...guMatch);

  // 군
  const gunMatch = address.match(/[가-힣]+군(?=[\s,]|$)/g);
  if (gunMatch) candidates.push(...gunMatch);

  // 시 (광역·특별·자치 제외)
  const siMatch = address.match(/[가-힣]+시(?=[\s,]|$)/g);
  if (siMatch) {
    for (const si of siMatch) {
      if (!si.includes("광역") && !si.includes("특별") && !si.includes("자치")) {
        candidates.push(si);
      }
    }
  }

  return Array.from(new Set(candidates));
}

/**
 * 부동산 주소로 관할 등기소명 반환
 * @example findCourtFromAddress("경기도 성남시 분당구 판교로 4") → "수원지방법원 성남지원 등기과"
 * @example findCourtFromAddress("경남 양산시 물금읍") → "울산지방법원 양산등기소"
 */
export function findCourtFromAddress(address: string): string {
  if (!address?.trim()) return "";

  const sido = parseSido(address);
  if (!sido) return "";

  const candidates = parseGungu(address, sido);
  if (!candidates.length) return "";

  for (const gungu of candidates) {
    const result = COURT_MAP[`${sido}_${gungu}`]
      ?? COURT_MAP[`${sido}_${gungu.replace(/\s+/g, "")}`];
    if (result) return result;
  }

  return "";
}

/**
 * 시도 코드와 구/군/시로 직접 조회
 * @example findCourtByRegion("경남", "양산시") → "울산지방법원 양산등기소"
 */
export function findCourtByRegion(sido: string, gungu: string): string {
  const normalizedSido = SIDO_ALIASES[sido] ?? sido;
  return COURT_MAP[`${normalizedSido}_${gungu}`] ?? "";
}
